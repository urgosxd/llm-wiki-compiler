"""
Entity page generation.

Pages are markdown documents synthesized from the compiled graph for
one entity at a time. Generated by gathering the entity's data and its
relationships, asking the LLM to write a wiki-style page, and caching
the result keyed by graph version.

Pages are NOT generated from the raw source documents. They are
generated from the compiled ontology. This is what makes pages
domain-aware — the LLM sees the entity's neighbors when writing.

Cache strategy:
  - graph_version is a hash of the entity's content + its relationships
  - any change to either invalidates the cache automatically
  - first request after invalidation regenerates and writes the cache
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from uuid import UUID

from psycopg2.extensions import connection as PGConnection

from app.core.config import config
from app.core.llm_clients import complete


def compute_graph_version(
    entity_row: dict,
    relationships: list[dict],
    contributing_doc_ids: list[UUID],
) -> str:
    """
    Stable hash of the entity's compiled state.

    Any change to the entity, its relationships, or its contributing
    documents produces a different hash. We use this as the cache key.
    """
    h = hashlib.sha256()
    h.update(entity_row["name"].encode())
    h.update((entity_row.get("description") or "").encode())
    h.update(str(float(entity_row["confidence"])).encode())
    h.update(json.dumps(entity_row.get("properties") or {}, sort_keys=True).encode())

    rel_repr = sorted([
        f"{r['type']}|{r['other_name']}|{float(r['confidence'])}"
        for r in relationships
    ])
    for rep in rel_repr:
        h.update(rep.encode())

    for doc_id in sorted(str(d) for d in contributing_doc_ids):
        h.update(doc_id.encode())

    return h.hexdigest()[:16]


def gather_entity_context(
    conn: PGConnection,
    entity_id: UUID,
) -> dict:
    """
    Pull everything needed to generate a page for one entity.
    Returns a dict with the entity row, outgoing and incoming
    relationships (with the other entity's name resolved), and a list
    of contributing document records.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            select id, stack_id, name, type, description, properties,
                   confidence, verified, last_seen_at
            from ontology_entities
            where id = %s
            """,
            (str(entity_id),),
        )
        entity = cur.fetchone()
        if not entity:
            return {}

        cur.execute(
            """
            select r.type, r.confidence, r.description,
                   e.name as other_name, e.type as other_type,
                   'outgoing' as direction
            from ontology_relationships r
            join ontology_entities e on e.id = r.to_entity_id
            where r.from_entity_id = %s
            order by r.confidence desc
            """,
            (str(entity_id),),
        )
        outgoing = [dict(r) for r in cur.fetchall()]

        cur.execute(
            """
            select r.type, r.confidence, r.description,
                   e.name as other_name, e.type as other_type,
                   'incoming' as direction
            from ontology_relationships r
            join ontology_entities e on e.id = r.from_entity_id
            where r.to_entity_id = %s
            order by r.confidence desc
            """,
            (str(entity_id),),
        )
        incoming = [dict(r) for r in cur.fetchall()]

        cur.execute(
            """
            select sd.id, sd.filename, sd.ingested_at
            from entity_source_documents esd
            join stack_documents sd on sd.id = esd.document_id
            where esd.entity_id = %s
            order by sd.ingested_at
            """,
            (str(entity_id),),
        )
        documents = [dict(r) for r in cur.fetchall()]

    return {
        "entity": dict(entity),
        "outgoing": outgoing,
        "incoming": incoming,
        "documents": documents,
    }


def generate_markdown(context: dict) -> str:
    """
    Generate the entity page markdown via one LLM call. The prompt
    is intentionally constraining: grounded synthesis, not creative
    expansion.
    """
    entity = context["entity"]
    outgoing = context["outgoing"]
    incoming = context["incoming"]
    documents = context["documents"]

    relationships_text_parts = []
    for r in outgoing:
        relationships_text_parts.append(
            f"  - This entity {r['type']}s {r['other_name']} "
            f"({r['other_type']}, confidence {float(r['confidence']):.2f})"
        )
    for r in incoming:
        relationships_text_parts.append(
            f"  - {r['other_name']} ({r['other_type']}) {r['type']}s this entity "
            f"(confidence {float(r['confidence']):.2f})"
        )
    relationships_text = "\n".join(relationships_text_parts) or "  (No relationships recorded)"

    documents_text = "\n".join(
        f"  - {d['filename']} (ingested {d['ingested_at'].date()})"
        for d in documents
    ) or "  (No contributing documents)"

    prompt = f"""You are writing a wiki-style markdown page for one entity in a compiled
knowledge graph. Use ONLY the information given. Do not invent facts.
Do not speculate beyond what the graph supports.

ENTITY:
  Name: {entity['name']}
  Type: {entity['type']}
  Confidence: {float(entity['confidence']):.2f}
  Existing description: {entity.get('description') or '(none)'}

RELATIONSHIPS:
{relationships_text}

CONTRIBUTING SOURCE DOCUMENTS:
{documents_text}

Write a markdown page following this structure:

# {entity['name']}

A 2-4 sentence summary of what this entity is and its role in the domain.
Reference its key relationships naturally. Do not list relationships verbatim;
weave them into prose.

## Relationships

A bulleted list grouping outgoing and incoming relationships, written in
plain English (e.g., "Triggers an On-Call response when declared", not
"triggers --> On-Call"). Group by direction. Skip this section entirely
if no relationships exist.

## Sources

A bulleted list of contributing documents with their filenames and
ingestion dates. Skip this section entirely if no documents contributed.

Return ONLY the markdown. No preamble, no explanation, no code fences."""

    return complete(prompt, max_tokens=2048)


def get_or_generate_page(
    conn: PGConnection,
    entity_id: UUID,
) -> dict:
    """
    Public entry point.

    1. Gather the entity's context from the graph
    2. Compute the current graph_version
    3. Check the cache. If hit and version matches, return cached page.
    4. Otherwise generate a new page, cache it, return it.
    """
    context = gather_entity_context(conn, entity_id)
    if not context:
        return {}

    entity = context["entity"]
    relationships = context["outgoing"] + context["incoming"]
    doc_ids = [d["id"] for d in context["documents"]]

    current_version = compute_graph_version(entity, relationships, doc_ids)

    with conn.cursor() as cur:
        cur.execute(
            """
            select markdown, graph_version, generated_at, source_type
            from entity_pages
            where entity_id = %s
            """,
            (str(entity_id),),
        )
        cached = cur.fetchone()

    if cached and cached["graph_version"] == current_version:
        return {
            "entity_name": entity["name"],
            "markdown": cached["markdown"],
            "generated_at": cached["generated_at"],
            "source_entity_id": entity_id,
            "graph_version": current_version,
            "source_type": cached["source_type"],
            "cached": True,
        }

    markdown = generate_markdown(context)
    generated_at = datetime.now(timezone.utc)

    with conn.cursor() as cur:
        cur.execute(
            """
            insert into entity_pages (
                entity_id, stack_id, entity_name, markdown,
                graph_version, source_type, generated_at,
                generated_by_model
            )
            values (%s, %s, %s, %s, %s, %s, %s, %s)
            on conflict (entity_id) do update set
                markdown = excluded.markdown,
                graph_version = excluded.graph_version,
                generated_at = excluded.generated_at,
                generated_by_model = excluded.generated_by_model,
                entity_name = excluded.entity_name
            """,
            (
                str(entity_id),
                str(entity["stack_id"]),
                entity["name"],
                markdown,
                current_version,
                "compiled",
                generated_at,
                config.EXTRACTION_MODEL,
            ),
        )

    return {
        "entity_name": entity["name"],
        "markdown": markdown,
        "generated_at": generated_at,
        "source_entity_id": entity_id,
        "graph_version": current_version,
        "source_type": "compiled",
        "cached": False,
    }
