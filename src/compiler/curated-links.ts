/**
 * @file Durable curated-link records: the model, its identity and its bounds (S8, S9, S12).
 *
 * The RECORD and its rules live here; the render-time rule that re-anchors a record onto a
 * fresh body is `curated-links-overlay.ts`, the confined store is
 * `curated-links-store.ts`, and the one shared application of both is
 * `curated-links-apply.ts`. This module knows nothing about files or page bodies: it is the
 * shape of the promise a review makes and the bounds on how many promises it may keep.
 *
 * THE DEFECT THIS EXISTS FOR. Stage 5 reviews earlier pages and, when the model says a
 * mention of a new article helps that page's reader, it edits the page body: the
 * mention becomes `[[target|mention]]`. That link then lives ONLY in generated bytes,
 * and page bodies are regenerated wholesale whenever the page's own source changes, so
 * the link disappears and returns only if the target article is reviewed again. Present
 * -> absent -> present with no source change is the oscillation, and it is not a
 * cosmetic bug: it makes the link graph a function of which source was ingested last.
 *
 * THE ASYMMETRY THAT HID IT. A mention of the target's TITLE is re-wrapped on every
 * render by the resolver's inbound/outbound pass (`resolver.ts` `addWikilinks` matches
 * page titles), so a title-anchored curated link comes back by itself. A mention of an
 * ALIAS has no such passive channel, so an alias-anchored link is destroyed by the very
 * next render. Alias-anchored links are therefore the reproducing case, and they are
 * the case the tests use: anything weaker would pass without touching the defect.
 *
 * THE RECORD IS OUTSIDE THE BODY, and it carries what a body cannot:
 *   - `sourcePageId` / `targetPageId`, both RESOLVED identities (`concepts/<slug>`), not
 *     the spelling the model wrote, because `link-repair` canonicalises spellings later;
 *   - `anchor`, the exact mention text plus the surrounding prose, so the link can be
 *     re-anchored in a body nobody has written yet;
 *   - `provenance`, WHICH channel accepted the link, because only the curated channel
 *     (`model-verdict`) may be overlaid -- a link the resolver or the repair pass
 *     derived mechanically is re-derivable on every render, and overlaying it would
 *     duplicate what those passes already do;
 *   - `stableKey` over (source, target, anchor), so re-reviewing the same mention cannot
 *     append a second identical record.
 *
 * THE OVERLAY RE-VALIDATES THE ANCHOR ON EVERY RENDER, which is what keeps S8 intact:
 * "No crees conexiones ... Los enlaces deben estar asociados a una mención o sección real
 * del artículo." The mention is looked for with the SAME rule that proposed it
 * ({@link firstPlainMention}, the retrieval primitive of `link-review-candidates.ts`), so
 * a proposal and its re-validation can never disagree about what a mention is. If the
 * words are gone, the link is NOT injected, the record is DROPPED, and the drop is
 * reported with its reason -- silently keeping an unanchored link would break S8, and
 * silently dropping it would reproduce the oscillation. Both directions are visible.
 *
 * THE OVERLAY IS IDEMPOTENT. A record already present as a link to its target is left
 * alone, so applying it twice equals applying it once and no page churns.
 *
 * THE BOUNDS ARE NAMED AND COUNTED (S12): {@link addCuratedLinks} enforces
 * `MAX_CURATED_LINKS_PER_PAGE` and `MAX_CURATED_LINKS_PER_RUN` and counts what each
 * dropped, and the overlay enforces the per-page bound again over whatever the store
 * holds. Nothing truncates silently.
 */

import { createHash } from "node:crypto";
import {
  CURATED_LINK_ANCHOR_CONTEXT_CHARS,
  MAX_CURATED_LINKS_PER_PAGE,
  MAX_CURATED_LINKS_PER_RUN,
} from "../utils/constants.js";
import type { PlainMention } from "./link-review-candidates.js";

/** The store layout this build writes and understands. */
export const CURATED_LINK_STORE_VERSION = 1;

/**
 * Which channel accepted a link.
 *
 * Only {@link CURATED_PROVENANCES} are overlaid. The other two are recorded here to
 * name them once: a `resolver-wrap` link is a plain mention of a page TITLE that
 * `addWikilinks` re-creates on every render, and a `repair` link is a written target
 * `link-repair` canonicalised. Both are DERIVED from the page text on every render, so
 * an overlay for them would either duplicate the derived link or pin a derivation that
 * is supposed to follow the text.
 */
export type CuratedLinkProvenance = "model-verdict" | "resolver-wrap" | "repair";

/** The provenances the overlay may act on: exactly the curated channels. */
export const CURATED_PROVENANCES: readonly CuratedLinkProvenance[] = ["model-verdict"];

/** The mention a curated link hangs on, with the prose around it. */
export interface CuratedLinkAnchor {
  /** The mention exactly as the page wrote it. */
  text: string;
  /** Prose before the mention, for an operator reading a drop report. */
  before: string;
  /** Prose after the mention, for the same reason. */
  after: string;
}

/** One durable curated link. */
export interface CuratedLinkRecord {
  /** Identity of this link: (source, target, anchor), so a re-review cannot duplicate it. */
  stableKey: string;
  /** Page the link lives ON, as a resolved page id (`concepts/alpha-topic`). */
  sourcePageId: string;
  /** Page the link points AT, as a resolved page id. */
  targetPageId: string;
  /** The mention the link must be re-anchored to on every render. */
  anchor: CuratedLinkAnchor;
  /** Which channel accepted it; only curated provenances are overlaid. */
  provenance: CuratedLinkProvenance;
  /** When the record was first made, for an operator reading the store. */
  createdAt: string;
}

/** The whole store, as `.llmwiki/curated-links.json` holds it. */
export interface CuratedLinkStore {
  /** Layout version; a file of another version is never written through. */
  version: number;
  /** Every durable curated link, in a deterministic order. */
  links: CuratedLinkRecord[];
}

/** Why the overlay refused to re-inject a record. Each reason is counted separately. */
export type CuratedLinkDropReason = "anchor-missing";

/** Why a record could not be stored. Each reason is counted separately. */
export type CuratedLinkTruncationReason = "page-cap" | "run-cap";

/** The truncation reasons, in reporting order. */
const CURATED_TRUNCATION_REASONS: readonly CuratedLinkTruncationReason[] = [
  "page-cap",
  "run-cap",
];
/** A run's curated-link bookkeeping, as the compile report reads it. */
export interface CuratedLinkCounts {
  /** Links the overlay re-injected into a regenerated body. */
  applied: number;
  /** New records the review stage stored. */
  recorded: number;
  /** Records refused by the anchor rule, per reason. */
  dropped: Record<CuratedLinkDropReason, number>;
  /** Records a bound refused to store or apply, per reason. */
  truncated: Record<CuratedLinkTruncationReason, number>;
}

/** Counts with nothing recorded, applied or refused yet. */
export function emptyCuratedLinkCounts(): CuratedLinkCounts {
  return {
    applied: 0,
    recorded: 0,
    dropped: { "anchor-missing": 0 },
    truncated: { "page-cap": 0, "run-cap": 0 },
  };
}

/** Fold one overlay or review outcome into a run's totals, in place. */
export function addCuratedLinkCounts(total: CuratedLinkCounts, counts: CuratedLinkCounts): void {
  total.applied += counts.applied;
  total.recorded += counts.recorded;
  total.dropped["anchor-missing"] += counts.dropped["anchor-missing"];
  for (const reason of CURATED_TRUNCATION_REASONS) total.truncated[reason] += counts.truncated[reason];
}

/** Whether anything was restored, recorded or refused, i.e. worth a report line. */
function hasCuratedLinkActivity(counts: CuratedLinkCounts): boolean {
  return counts.applied > 0
    || counts.recorded > 0
    || counts.dropped["anchor-missing"] > 0
    || CURATED_TRUNCATION_REASONS.some((reason) => counts.truncated[reason] > 0);
}

/**
 * One line describing the run's curated links, or null when nothing happened.
 *
 * Silence means the run had no curated record to restore, stored none and refused
 * none -- the ordinary case for a wiki whose pages were not regenerated. A dropped
 * record and a fired bound are both named with their own counts, because a limit or a
 * lost link that nobody can see is the defect S12 forbids.
 *
 * @param counts - The run's curated-link totals.
 * @returns The summary text, or null when there is nothing to report.
 */
export function describeCuratedLinks(counts: CuratedLinkCounts): string | null {
  if (!hasCuratedLinkActivity(counts)) return null;
  const parts = [`${counts.applied} link(s) restored`];
  if (counts.recorded > 0) parts.push(`${counts.recorded} record(s) kept`);
  const dropped = counts.dropped["anchor-missing"];
  if (dropped > 0) parts.push(`${dropped} dropped (${dropped} anchor-missing)`);
  const truncated = CURATED_TRUNCATION_REASONS
    .filter((reason) => counts.truncated[reason] > 0)
    .map((reason) => `${counts.truncated[reason]} ${reason}`);
  if (truncated.length > 0) parts.push(`truncated ${truncated.join(", ")}`);
  return parts.join(", ");
}

/**
 * The identity of one curated link.
 *
 * A hash rather than a concatenation so the key is one opaque token in the store and in
 * a report, and so two anchors that differ only in surrounding prose are DIFFERENT
 * links while a re-review of the same mention is the same one. Case and internal
 * whitespace are folded because {@link firstPlainMention} matches case-insensitively, so
 * `Vector  Database` and `vector database` can only ever anchor the same words.
 *
 * @param sourcePageId - Page the link lives on.
 * @param targetPageId - Page the link points at.
 * @param anchorText - The mention the link hangs on.
 * @returns A stable 16-hex-character key.
 */
export function curatedLinkKey(
  sourcePageId: string,
  targetPageId: string,
  anchorText: string,
): string {
  const folded = anchorText.trim().replace(/\s+/gu, " ").toLowerCase();
  return createHash("sha256")
    .update(`${sourcePageId}\u0000${targetPageId}\u0000${folded}`)
    .digest("hex")
    .slice(0, 16);
}

/**
 * Build one record, minting its stable key from the three identities it joins.
 *
 * @param input - The resolved ids, the anchor and the accepting channel.
 * @returns The record to store.
 */
export function createCuratedLink(input: {
  sourcePageId: string;
  targetPageId: string;
  anchor: CuratedLinkAnchor;
  provenance: CuratedLinkProvenance;
  createdAt?: string;
}): CuratedLinkRecord {
  return {
    stableKey: curatedLinkKey(input.sourcePageId, input.targetPageId, input.anchor.text),
    sourcePageId: input.sourcePageId,
    targetPageId: input.targetPageId,
    anchor: input.anchor,
    provenance: input.provenance,
    createdAt: input.createdAt ?? new Date().toISOString(),
  };
}

/**
 * The anchor of a mention found in a body, with the prose around it.
 *
 * The surrounding window is clipped to `CURATED_LINK_ANCHOR_CONTEXT_CHARS` per side: it
 * exists so a human reading the store or a drop report can see the sentence the link was
 * justified by, not so the link can be pinned to a paragraph no render will reproduce.
 *
 * @param body - The body the mention was found in.
 * @param mention - The span {@link firstPlainMention} reported.
 * @returns The anchor to store.
 */
export function anchorAround(body: string, mention: PlainMention): CuratedLinkAnchor {
  const start = Math.max(0, mention.start - CURATED_LINK_ANCHOR_CONTEXT_CHARS);
  const end = Math.min(body.length, mention.end + CURATED_LINK_ANCHOR_CONTEXT_CHARS);
  return {
    text: mention.text,
    before: body.slice(start, mention.start),
    after: body.slice(mention.end, end),
  };
}

/** Whether a record belongs to a channel the overlay may act on. */
export function isCurated(record: CuratedLinkRecord): boolean {
  return CURATED_PROVENANCES.includes(record.provenance);
}

/** The bare slug of a namespaced page id (`concepts/networks` -> `networks`). */
export function slugOfPageId(pageId: string): string {
  const separator = pageId.lastIndexOf("/");
  return separator === -1 ? pageId : pageId.slice(separator + 1);
}

/**
 * Store new records, deduplicating by key and holding both named bounds.
 *
 * A record the store already holds under the same key is NOT appended: re-reviewing the
 * same mention is the same link, and appending it again would grow the store on every
 * ingest that reviewed the page. A record past {@link MAX_CURATED_LINKS_PER_PAGE} for its
 * page, or past {@link MAX_CURATED_LINKS_PER_RUN} for this run, is refused and counted --
 * never dropped silently (S12).
 *
 * The returned store is DETERMINISTICALLY ORDERED (source page, then target page, then
 * stable key), so two runs that hold the same set write identical bytes.
 *
 * @param store - The store as read.
 * @param incoming - Records this run produced, in the order the review accepted them.
 * @param tally - Counters to fill: what was stored and what a bound refused.
 * @returns The store to write.
 */
export function addCuratedLinks(
  store: CuratedLinkStore,
  incoming: readonly CuratedLinkRecord[],
  tally: CuratedLinkCounts,
): CuratedLinkStore {
  const links = [...store.links];
  const known = new Set(links.map((record) => record.stableKey));
  const perPage = new Map<string, number>();
  for (const record of links) {
    perPage.set(record.sourcePageId, (perPage.get(record.sourcePageId) ?? 0) + 1);
  }
  let added = 0;
  for (const record of incoming) {
    if (known.has(record.stableKey)) continue;
    if ((perPage.get(record.sourcePageId) ?? 0) >= MAX_CURATED_LINKS_PER_PAGE) {
      tally.truncated["page-cap"] += 1;
      continue;
    }
    if (added >= MAX_CURATED_LINKS_PER_RUN) {
      tally.truncated["run-cap"] += 1;
      continue;
    }
    known.add(record.stableKey);
    perPage.set(record.sourcePageId, (perPage.get(record.sourcePageId) ?? 0) + 1);
    links.push(record);
    added += 1;
  }
  tally.recorded += added;
  return { version: CURATED_LINK_STORE_VERSION, links: sortLinks(links) };
}

/**
 * The store's canonical order: by source page, then target page, then key.
 *
 * A function of the SET, never of insertion order, so the same links always produce the
 * same file bytes and a re-run of an unchanged review changes nothing.
 *
 * @param links - Records in any order.
 * @returns The same records in the canonical order.
 */
export function sortLinks(links: readonly CuratedLinkRecord[]): CuratedLinkRecord[] {
  return [...links].sort(compareLinks);
}

/** Total order over records, by UTF-16 code unit so no locale can change it. */
function compareLinks(left: CuratedLinkRecord, right: CuratedLinkRecord): number {
  const page = compareText(left.sourcePageId, right.sourcePageId);
  if (page !== 0) return page;
  const target = compareText(left.targetPageId, right.targetPageId);
  return target !== 0 ? target : compareText(left.stableKey, right.stableKey);
}

/** Compare two ids by code unit. */
function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}
