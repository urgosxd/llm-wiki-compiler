/** Shape of one recorded request. */
interface RecordedRequest {
  readonly url: string;
  readonly body: unknown;
}

const recorded: RecordedRequest[] = [];

/** Embedding requests served by the fake, in call order. */
let embeddingResponses: Array<(inputs: readonly string[]) => unknown> = [];
/** Chat-completion responses served by the fake, in call order. */
let chatResponses: Array<(body: Record<string, unknown>) => unknown> = [];
/** When set, the fake answers 500 instead of a body. */
let failChat = false;

const EMBEDDING_DIM = 768;
const STACK_ID = "aaaaaaaa-0000-4000-8000-00000000aaaa";
const DOCUMENT_ID = "bbbbbbbb-0000-4000-8000-00000000bbbb";

function jsonResponse(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json" },
  });
}

/** Installs the fake `fetch`. */
function installFetchStub(): void {
  vi.stubGlobal(
    "fetch",
    async (input: string | URL | Request, init?: RequestInit): Promise<Response> => {
      const url = typeof input === "string" ? input : input instanceof URL ? input.href : input.url;
      const rawBody = typeof init?.body === "string" ? init.body : "{}";
      const body: unknown = JSON.parse(rawBody);
      recorded.push({ url, body });

      if (url.endsWith("/embeddings")) {
        const inputs = (body as { input?: string[] }).input ?? [];
        const responder = embeddingResponses.shift();
        if (responder === undefined) {
          return jsonResponse({ data: inputs.map((_, index) => ({ index, embedding: fakeVector() })) });
        }
        return jsonResponse(responder(inputs));
      }

      if (url.endsWith("/chat/completions")) {
        if (failChat) {
          return jsonResponse({ error: { message: "stub failure" } }, 500);
        }
        const rec = body as Record<string, unknown>;
        const responder = chatResponses.shift();
        if (responder === undefined) {
          return jsonResponse(toolCallResponse({ triplets: [] }));
        }
        return jsonResponse(responder(rec));
      }

      return jsonResponse({ error: { message: `unexpected url ${url}` } }, 404);
    },
  );
}

function uninstallFetchStub(): void {
  vi.unstubAllGlobals();
  recorded.length = 0;
  embeddingResponses = [];
  chatResponses = [];
  failChat = false;
}

/** A deterministic unit-ish vector of the production dimension. */
function fakeVector(): number[] {
  return Array.from({ length: EMBEDDING_DIM }, (_, index) => (index % 7) / 7);
}

/** An OpenAI-compatible chat response carrying a tool call with `payload`. */
function toolCallResponse(payload: unknown): unknown {
  return {
    choices: [
      {
        message: {
          role: "assistant",
          content: null,
          tool_calls: [
            {
              type: "function",
              function: { name: "KGSchema", arguments: JSON.stringify(payload) },
            },
          ],
        },
      },
    ],
  };
}

/** Queues one embedding responder. Defaults to echoing a fake vector per input. */
function setEmbeddingResponse(responder?: (inputs: readonly string[]) => unknown): void {
  embeddingResponses.push(responder ?? ((inputs) => ({
    data: inputs.map((_, index) => ({ index, embedding: fakeVector() })),
  })));
}

/** Queues one chat responder that returns `payload` as a tool call. */
function setToolResponse(payloads: readonly unknown[]): void {
  for (const payload of payloads) {
    chatResponses.push(() => toolCallResponse(payload));
  }
}

/** Makes the next chat call fail with a provider error. */
function setToolFailure(): void {
  failChat = true;
}

function embeddingCalls(): number {
  return recorded.filter((entry) => entry.url.endsWith("/embeddings")).length;
}

function toolCalls(): number {
  return recorded.filter((entry) => entry.url.endsWith("/chat/completions")).length;
}

/** The prompt of the most recent chat call, read out of its messages. */
function lastToolPrompt(): string {
  const chat = recorded.filter((entry) => entry.url.endsWith("/chat/completions")).at(-1);
  const messages = (chat?.body as { messages?: Array<{ content?: string }> } | undefined)?.messages;
  return messages?.[0]?.content ?? "";
}

/** Convenience wrappers used by the pipeline suites. */
function stubEmbeddings(): void {
  setEmbeddingResponse();
}
function restoreEmbeddings(): void {
  uninstallFetchStub();
  installFetchStub();
}
function stubToolCall(): void {
  // The fake falls back to answering every chunk with an empty triplet list when
  // no responder is queued, so nothing has to be set up for the cost tests.
  chatResponses = [];
  failChat = false;
}
function restoreToolCall(): void {
  uninstallFetchStub();
  installFetchStub();
}

