/**
 * Parity tests for the MCP server port (`app/mcp_server.py`).
 *
 * ## There is no runnable Python MCP oracle, by design of this suite
 *
 * `app/mcp_server.py` cannot be imported in this repo: it does
 * `from mcp.server import Server` (→ `mcp.server.lowlevel.server.Server`) while
 * `requirements.txt` installs unpinned `mcp`, which resolves to 2.3.0 — a
 * version with no `list_tools`/`call_tool` methods — so execution dies at the
 * `@server.list_tools()` decorator. Reproduced against the live container:
 * `AttributeError: 'Server' object has no attribute 'list_tools'`.
 *
 * A second, independent defect sits behind it: `call_tool` invokes
 * `_list_stacks()` while the handler requires `args`, raising
 * `TypeError: missing 1 required positional argument: 'args'`.
 *
 * Neither is reproduced by this port (see the module header in `mcp.ts`). The
 * consequence for *testing* is what matters here: no tool's end-to-end behavior
 * can be observed from the Python server, so "diff against the oracle" is not
 * available for any of the four tools. What remains verifiable, and how:
 *
 * 1. **The advertisement** is compared against the Python's own literal
 *    `Tool(...)` definitions, extracted from the source with `ast` rather than
 *    retyped, and embedded verbatim in `PYTHON_TOOLS_JSON` below. (This is the
 *    only sound source of truth precisely because the module never imports.)
 * 2. **The formatters** are pure functions of JSON, so their expected output is
 *    the *actual* text CPython's `_format_*` functions produce for the same
 *    input. Every `EXPECTED_*` constant below was generated by executing the
 *    original Python functions — loaded with `ast`, bypassing the broken
 *    import — not written by hand.
 * 3. **The routing and auth header** are checked against a recording stub
 *    `fetch`, asserting the exact URL, HTTP method, body and headers the Python
 *    constructs via httpx.
 * 4. **A real MCP handshake** runs over the SDK's in-memory transport, so
 *    `tools/list` and `tools/call` go through the actual protocol layer.
 *
 * Shape fixtures split into two groups, labelled at each use: **REAL** bodies
 * captured from `localhost:8000`, and **SYNTHETIC** bodies of the documented
 * OpenAPI shape (the oracle holds no entities, and `/aks/v1/context` answers 500
 * for want of LLM credentials).
 */

