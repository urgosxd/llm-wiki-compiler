interface RecordedRequest {
  readonly url: string;
  readonly method: string;
  readonly headers: Record<string, string>;
  readonly body: string | undefined;
}

interface StubResponse {
  readonly status: number;
  readonly body: string;
}

/** Build a `FetchLike` that records every request and replays one response. */
function recordingFetch(response: StubResponse): {
  fetchImpl: FetchLike;
  requests: RecordedRequest[];
} {
  const requests: RecordedRequest[] = [];
  const fetchImpl: FetchLike = async (url, init) => {
    requests.push({
      url,
      method: init.method,
      headers: init.headers,
      body: init.body,
    });
    return {
      status: response.status,
      text: async () => response.body,
      json: async () => JSON.parse(response.body) as unknown,
    };
  };
  return { fetchImpl, requests };
}

/** Narrow a tool result to its single text block. */
function textOf(result: CallToolResult): string {
  expect(result.content).toHaveLength(1);
  const [first] = result.content;
  if (first === undefined || first.type !== "text") {
    throw new Error("Expected a single text content block");
  }
  return first.text;
}

