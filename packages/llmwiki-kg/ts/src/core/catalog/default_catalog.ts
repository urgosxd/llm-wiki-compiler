/**
 * @file packages/llmwiki-kg/ts/src/core/catalog/default_catalog.ts
 * @description The documented example catalog this application ships.
 *
 * ## Why a default catalog exists
 *
 * A Stack that configures no catalog still needs one to classify against, and
 * the alternative to a documented example is a guess buried in the pipeline. This
 * is that example: five entity types and the five relations the request names,
 * each with a definition and examples so a classifier is oriented by meaning
 * rather than by a bare label, plus the five permitted type combinations.
 *
 * ## This is configuration, not a standard
 *
 * Every name here is OUR vocabulary. AKS declares no global type enum
 * (`SCHEMA.json:499`, `SCHEMA.json:582`), and nothing in this file proposes a new
 * AKS profile: a Stack may replace the whole catalog, and items that match none
 * of it stay free rather than being coerced into one of these types.
 *
 * ## Why it is validated and frozen once
 *
 * The declaration is parsed through the same {@link parseTypeCatalog} a Stack's
 * stored catalog goes through, so the shipped example cannot be a shape the rest
 * of the code would reject, and the reserved {@link UNCLASSIFIED_ENTITY_TYPE}
 * cannot appear in it. The result is deep-frozen by the parser, which is what
 * makes returning one shared instance safe: there is no mutator to reach it with,
 * so no ingest can widen the default vocabulary (S16).
 */

import { parseTypeCatalog } from "./parse.js";
import type { TypeCatalog } from "./types.js";

/**
 * The entity types the default catalog declares.
 *
 * `Role`, `Process`, `Document`, `Policy` and `System` are the five the request
 * names. They are deliberately few: a small catalog with real definitions
 * classifies more honestly than a long list of near-synonyms, and anything that
 * fits none of them stays free instead of being stretched into the nearest type.
 */
const ENTITY_TYPES = [
  {
    name: "Role",
    definition:
      "A responsibility, position or function held by a person or a team inside a process: who acts, who approves, who is accountable.",
    examples: ["Incident Commander", "Data Protection Officer", "Change approver"],
  },
  {
    name: "Process",
    definition:
      "An ordered set of activities that produces an outcome, including procedures, workflows, routines and review cycles.",
    examples: ["Change management", "Quarterly access review", "Incident response"],
  },
  {
    name: "Document",
    definition:
      "A written artifact that records information, decisions, instructions or evidence, whether authored by a person or generated by a system.",
    examples: ["Runbook", "Meeting minutes", "Architecture decision record"],
  },
  {
    name: "Policy",
    definition:
      "A binding rule, obligation or constraint that mandates or forbids behaviour, including standards, regulations and internal rules.",
    examples: ["Retention policy", "Password standard", "GDPR Article 32"],
  },
  {
    name: "System",
    definition:
      "A software, infrastructure or tooling component that performs work or provides a capability another element depends on.",
    examples: ["Billing service", "PostgreSQL cluster", "Identity provider"],
  },
] as const;

/**
 * The relation types the default catalog declares.
 *
 * Each verb is stated in the active voice — the canonical reading runs from the
 * subject to the object — which is why every one declares
 * `direction: "forward"`. A predicate a document phrases passively is expected to
 * arrive through an alias or to stay free; it is never rewritten in place.
 */
const RELATION_TYPES = [
  {
    name: "executes",
    definition:
      "The subject role carries out, owns or performs the object process, and is accountable for its outcome.",
    direction: "forward",
    examples: ["Incident Commander executes Incident response"],
  },
  {
    name: "reviews",
    definition:
      "The subject role examines the object document and produces a judgement about it, such as approval or rejection.",
    direction: "forward",
    examples: ["Change approver reviews Architecture decision record"],
  },
  {
    name: "requires",
    definition:
      "The subject process depends on the object document as an input or a precondition for running or completing.",
    direction: "forward",
    examples: ["Change management requires Runbook"],
  },
  {
    name: "governs",
    definition:
      "The subject policy constrains how the object process may be performed, including which approvals it needs.",
    direction: "forward",
    examples: ["Retention policy governs Quarterly access review"],
  },
  {
    name: "supports",
    definition:
      "The subject system provides a capability the object process depends on to run, or runs part of it directly.",
    direction: "forward",
    examples: ["Identity provider supports Incident response"],
  },
] as const;

/**
 * The five permitted `(from, relation, to)` combinations, one per relation.
 *
 * Each relation declares exactly one combination because that is the whole claim
 * the request makes about it: `Role —executes→ Process`, `Role —reviews→
 * Document`, `Process —requires→ Document`, `Policy —governs→ Process`,
 * `System —supports→ Process`. Narrowing a combination is a catalog edit and a
 * version bump, never an ingestion-side decision.
 */
const CONSTRAINTS = [
  { from: "Role", relation: "executes", to: "Process" },
  { from: "Role", relation: "reviews", to: "Document" },
  { from: "Process", relation: "requires", to: "Document" },
  { from: "Policy", relation: "governs", to: "Process" },
  { from: "System", relation: "supports", to: "Process" },
] as const;

/**
 * Labels an extractor plausibly proposes for each canonical type.
 *
 * These are orientation, not coercion: an alias only resolves when the catalog
 * declares it, and resolving one never widens the catalog. They exist because the
 * same type is written as `Position`, `position` or `carries out` in real
 * documents, and a human maintaining this file can see at a glance what each type
 * already absorbs.
 */
const ENTITY_ALIASES = [
  { alias: "position", canonical: "Role" },
  { alias: "function", canonical: "Role" },
  { alias: "procedure", canonical: "Process" },
  { alias: "workflow", canonical: "Process" },
  { alias: "artifact", canonical: "Document" },
  { alias: "record", canonical: "Document" },
  { alias: "standard", canonical: "Policy" },
  { alias: "regulation", canonical: "Policy" },
  { alias: "service", canonical: "System" },
  { alias: "application", canonical: "System" },
] as const;

/** Predicates that normalize to a canonical relation of the default catalog. */
const RELATION_ALIASES = [
  { alias: "performs", canonical: "executes" },
  { alias: "carries out", canonical: "executes" },
  { alias: "is executed by", canonical: "executes" },
  { alias: "checks", canonical: "reviews" },
  { alias: "needs", canonical: "requires" },
  { alias: "depends on", canonical: "requires" },
  { alias: "regulates", canonical: "governs" },
  { alias: "enables", canonical: "supports" },
] as const;

/**
 * The version of the shipped declaration.
 *
 * Bumping it is how a vocabulary change becomes traceable: stored classification
 * decisions record the version they were produced under, so a reclassification
 * run can find the ones a bump invalidated. Treat any edit to the lists above as
 * a version change, including one that only adds an alias.
 */
const DEFAULT_CATALOG_VERSION = "1.0.0";

/** The validated, deeply frozen default catalog, built once per process. */
const DEFAULT_CATALOG: TypeCatalog = parseTypeCatalog({
  version: DEFAULT_CATALOG_VERSION,
  entityTypes: ENTITY_TYPES,
  relationTypes: RELATION_TYPES,
  constraints: CONSTRAINTS,
  entityAliases: ENTITY_ALIASES,
  relationAliases: RELATION_ALIASES,
});

/**
 * The documented example catalog, validated and immutable.
 *
 * Returns a shared instance because the value cannot be mutated: the parser
 * deep-froze it, and `TypeCatalog` exposes no mutator. A caller that wants a
 * different vocabulary writes its own declaration; it cannot change what this
 * function returns, and ingestion cannot extend it (S16).
 *
 * @returns The five-type, five-relation default catalog.
 */
export function defaultTypeCatalog(): TypeCatalog {
  return DEFAULT_CATALOG;
}
